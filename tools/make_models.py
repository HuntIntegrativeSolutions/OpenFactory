def conveyor_frame() -> dict[str, Geometry]:
    """belt_conveyor and roller_conveyor frame, in the conveyor's local frame (+x the flow, y up,
    the belt top at y 0). ``rail``: one side rail, a channel 0.08 m deep with its flanges toward
    -z (the viewer mirrors it for the +z side), from x 0 to 1 (stretched to the conveyor's length),
    its top 0.01 m above the belt as the primitive's. ``leg``: a 0.05 m square tube from y 0 down
    to y -1 (stretched to the height above the floor). ``foot``: the floor plate under a leg on a
    rubber pad, from the floor at y 0 to y 0.012. ``crossbar``: a brace between a leg pair,
    z -0.5 to 0.5 (stretched to the frame's width). ``drum``: a belt end drum along z, -0.5 to
    0.5 (stretched to the belt width), with ``bearing``: the block outside the rail holding a
    drum's shaft, one per side."""
    rail = Geometry()
    web, flange, depth = 0.006, 0.03, 0.08
    rail.box(FRAME, (0, -depth + 0.01, -web / 2), (1, 0.01, web / 2))  # the web
    for y in (0.01 - 0.006, -depth + 0.01):  # top and bottom flanges, toward -z
        rail.box(FRAME, (0, y, -flange + web / 2), (1, y + 0.006, web / 2))
    leg = Geometry().box(FRAME, (-0.025, -1, -0.025), (0.025, 0, 0.025))
    foot = Geometry().box(BLACK, (-0.045, 0, -0.045), (0.045, 0.004, 0.045))  # rubber pad
    foot.box(DARK, (-0.05, 0.004, -0.05), (0.05, 0.012, 0.05))
    crossbar = Geometry().box(FRAME, (-0.015, -0.03, -0.5), (0.015, 0, 0.5))
    drum = Geometry().cylinder(STRUCTURE, 2, (0, 0, 0), 0.04, 1)
    bearing = Geometry().box(DARK, (-0.035, -0.03, -0.02), (0.035, 0.03, 0.02))
    bearing.cylinder(BLACK, 2, (0, 0, 0.02), 0.012, 0.012, 12)  # shaft end
    return {"rail": rail, "leg": leg, "foot": foot, "crossbar": crossbar, "drum": drum,
            "bearing": bearing}  # fmt: skip


def photo_eye() -> dict[str, Geometry]:
    """photo_eye heads, in a head's own frame: the lens on the +z face, toward the beam (the viewer
    turns the far head 180 degrees). ``head``: a 0.05 x 0.09 x 0.04 m housing, the primitive's
    size, with a dark face plate, a black lens and a cable gland under it. ``bracket``: the angle
    bracket behind a head that holds it to the guard rail."""
    head = Geometry().box(FRAME, (-0.025, -0.045, -0.02), (0.025, 0.045, 0.016))
    head.box(DARK, (-0.022, -0.042, 0.016), (0.022, 0.042, 0.02))  # face plate
    head.cylinder(BLACK, 2, (0, 0.012, 0.022), 0.011, 0.004, 16)  # lens
    head.cylinder(BLACK, 1, (0, -0.052, 0), 0.007, 0.014, 12)  # cable gland
    bracket = Geometry().box(DARK, (-0.03, -0.03, -0.026), (0.03, 0.03, -0.02))
    bracket.box(DARK, (-0.03, -0.036, -0.06), (0.03, -0.03, -0.02))
    return {"head": head, "bracket": bracket}


def pusher() -> dict[str, Geometry]:
    """pusher (a pneumatic cylinder), in the pusher's local frame: the plate face at the origin, the
    plate extending along +z, the housing behind it along -z. ``barrel``: the round aluminium tube,
    0.04 m radius, from z 0 to -1 (stretched to the stroke). ``tie_rods``: the four rods at the
    caps' corners, z 0 to -1 (stretched). ``front_cap`` and ``rear_cap``: 0.12 m square caps,
    0.04 m deep, from z 0 to -0.04; the front one has the rod gland, the rear one an air port
    (the front cap's port is on the top face too). ``foot``: a mounting foot under a cap, from
    the cap's outer face at z 0 along the barrel to z -0.1 (mirrored for the rear cap)."""
    barrel = Geometry().cylinder(ALUMINIUM, 2, (0, 0, -0.5), 0.04, 1, 24)
    rods = Geometry()
    for x in (-0.05, 0.05):
        for y in (-0.05, 0.05):
            rods.cylinder(ALUMINIUM, 2, (x, y, -0.5), 0.006, 1, 10)
    front = Geometry().box(DARK, (-0.06, -0.06, -0.04), (0.06, 0.06, 0))
    front.cylinder(BLACK, 2, (0, 0, 0.006), 0.022, 0.012, 20)  # rod gland
    front.cylinder(BLACK, 1, (0, 0.066, -0.02), 0.008, 0.012, 12)  # air port
    rear = Geometry().box(DARK, (-0.06, -0.06, -0.04), (0.06, 0.06, 0))
    rear.cylinder(BLACK, 1, (0, 0.066, -0.02), 0.008, 0.012, 12)  # air port
    foot = Geometry().box(DARK, (-0.09, -0.085, -0.1), (0.09, -0.06, 0))
    return {"barrel": barrel, "tie_rods": rods, "front_cap": front, "rear_cap": rear, "foot": foot}


def stopper() -> dict[str, Geometry]:
    """stopper actuator, centered where the primitive's 0.08 x 0.06 x 0.12 m box hangs under the
    belt (the viewer places it at the blade's x, 0.11 m below the belt top). ``actuator``: a
    dark flange plate on top (y 0.024 to 0.03) that bolts under the conveyor, a square
    aluminium cylinder body below it, a round barrel end, and two air ports on the upstream
    face. The blade stays a primitive."""
    actuator = Geometry().box(DARK, (-0.04, 0.024, -0.06), (0.04, 0.03, 0.06))
    actuator.box(ALUMINIUM, (-0.032, -0.012, -0.032), (0.032, 0.024, 0.032))
    actuator.cylinder(ALUMINIUM, 1, (0, -0.021, 0), 0.026, 0.018, 24)
    for z in (-0.014, 0.014):
        actuator.cylinder(BLACK, 0, (-0.036, 0.008, z), 0.006, 0.008, 12)
    return {"actuator": actuator}


def turntable() -> dict[str, Geometry]:
    """turntable pedestal, in the turntable's local frame turned about its pivot (y up).
    ``bearing``: the slewing-ring housing under the platform, 0.12 m radius, from y 0 down to
    -0.03. ``column``: the round pedestal tube, 0.07 m radius, from y 0 down to -1 (stretched
    to the height above the floor). ``base``: the floor plate, 0.32 m square, on a rubber pad,
    from the floor at y 0 to y 0.016, with a gusset collar around the column."""
    bearing = Geometry().cylinder(STRUCTURE, 1, (0, -0.015, 0), 0.12, 0.03, 40)
    bearing.cylinder(DARK, 1, (0, -0.033, 0), 0.1, 0.006, 40)
    column = Geometry().cylinder(FRAME, 1, (0, -0.5, 0), 0.07, 1, 32)
    base = Geometry().box(BLACK, (-0.155, 0, -0.155), (0.155, 0.004, 0.155))
    base.box(DARK, (-0.16, 0.004, -0.16), (0.16, 0.016, 0.16))
    base.cylinder(DARK, 1, (0, 0.031, 0), 0.09, 0.03, 32)
    return {"bearing": bearing, "column": column, "base": base}


def diverter_arm() -> dict[str, Geometry]:
    """diverter_arm drive, in the arm's local frame with the origin at the pivot axis at the top
    of the paddle (y 0), where the primitive's pivot post starts. ``drive``: an aluminium hub
    (0.035 m radius, y 0 to 0.025), a dark right-angle gearbox above it (y 0.025 to 0.06), and
    the motor behind the pivot along -x, away from the arm at rest."""
    drive = Geometry().cylinder(ALUMINIUM, 1, (0, 0.0125, 0), 0.035, 0.025, 24)
    drive.box(DARK, (-0.04, 0.025, -0.04), (0.04, 0.06, 0.04))
    drive.cylinder(FRAME, 0, (-0.075, 0.0425, 0), 0.024, 0.07, 20)
    drive.cylinder(BLACK, 0, (-0.112, 0.0425, 0), 0.016, 0.004, 16)  # motor end cap
    return {"drive": drive}


def _panel(face: Geometry) -> Geometry:
    """The enclosure every operator device sits in: a 0.08 m square front plate, 0.02 m deep,
    its front face at z -0.02 (the primitive plate's), and a legend plate under the operator."""
    face.box(FRAME, (-0.04, -0.04, -0.04), (0.04, 0.04, -0.02))
    face.box(DARK, (-0.024, -0.039, -0.02), (0.024, -0.033, -0.018))  # legend plate
    return face


def pushbutton() -> dict[str, Geometry]:
    """pushbutton, in the button's local frame (the face toward +z). ``panel``: the enclosure
    with an aluminium guard collar around the cap (0.033 m radius, z -0.02 to -0.014), so the
    cap, which shows the button's color and moves when pressed, stays a primitive."""
    panel = _panel(Geometry())
    panel.cylinder(ALUMINIUM, 2, (0, 0, -0.017), 0.033, 0.006, 32)
    return {"panel": panel}


def pilot_light() -> dict[str, Geometry]:
    """pilot_light, in the light's local frame (the lens toward +z). ``panel``: the enclosure
    with a knurled-look aluminium bezel ring (0.034 m radius, z -0.02 to -0.011); the lens,
    which lights, stays a primitive."""
    panel = _panel(Geometry())
    panel.cylinder(ALUMINIUM, 2, (0, 0, -0.0155), 0.034, 0.009, 12)  # 12 flats read as knurls
    return {"panel": panel}


def selector_switch() -> dict[str, Geometry]:
    """selector_switch, in the switch's local frame (the handle toward +z). ``panel``: the
    enclosure with a dark bezel (0.03 m radius, z -0.02 to 0, the primitive bezel's) and three
    light index marks on the plate at the a, center and b positions (45 degrees either side of
    up, as the handle turns); the handle, which an operator turns, stays a primitive."""
    panel = _panel(Geometry())
    panel.cylinder(DARK, 2, (0, 0, -0.01), 0.03, 0.02, 32)
    for angle in (-45, 0, 45):
        a = math.radians(angle)
        x, y = round(-0.035 * math.sin(a), 6), round(0.035 * math.cos(a), 6)
        panel.box(ALUMINIUM, (x - 0.002, y - 0.002, -0.02), (x + 0.002, y + 0.002, -0.018))
    return {"panel": panel}


MODELS: dict[str, Callable[[], dict[str, Geometry]]] = {
    "conveyor_frame": conveyor_frame,
    "photo_eye": photo_eye,
    "pusher": pusher,
    "stopper": stopper,
    "turntable": turntable,
    "diverter_arm": diverter_arm,
    "pushbutton": pushbutton,
    "pilot_light": pilot_light,
    "selector_switch": selector_switch,
}


def build(name: str) -> bytes:
    return glb(MODELS[name](), "tools/make_models.py")


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Write the viewer's default models (PLAN 4.2).")
    parser.add_argument("--check", action="store_true", help="exit 1 if a committed file differs")
    args = parser.parse_args(argv)
    stale = []
    for name in MODELS:
        data, path = build(name), OUT_DIR / f"{name}.glb"
        sidecar = path.with_name(path.name + ".license.txt")
        text = LICENSE.format(name=name)
        if args.check:
            if not path.is_file() or path.read_bytes() != data:
                stale.append(path)
            if not sidecar.is_file() or sidecar.read_text(encoding="utf-8") != text:
                stale.append(sidecar)
            continue
        OUT_DIR.mkdir(parents=True, exist_ok=True)
        path.write_bytes(data)
        sidecar.write_text(text, encoding="utf-8")
        print(f"wrote {path.relative_to(REPO)} ({len(data)} bytes)")
    for path in stale:
        print(f"{path.relative_to(REPO)} is stale; run: uv run python tools/make_models.py",
              file=sys.stderr)  # fmt: skip
    return 1 if stale else 0


if __name__ == "__main__":
    raise SystemExit(main())
