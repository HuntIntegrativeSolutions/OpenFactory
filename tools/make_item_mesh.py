"""Write the example item mesh, ``scenes/examples/models/mixer-drive.glb`` (PLAN 5.2c).

Usage::

    uv run python tools/make_item_mesh.py            # rewrite the file and its license sidecar
    uv run python tools/make_item_mesh.py --check    # exit 1 if a committed file differs

The mesh is ours (HIS Controls, CC-BY-4.0; ``mixer-drive.glb.license.txt`` beside it), built
here from boxes and cylinders with ``tools/make_models.py``'s geometry and GLB writer, so no
outside asset is involved: a generic geared motor drive on a base plate, the body of the
``variable_item`` instance ``MX_02`` in ``scenes/examples/variable-item-demo.yaml``. It is drawn
in the ``scenery`` body's frame (origin at the centre of its box, PLAN 5.2c) for a body of 1.0 m
by 0.8 m by 0.6 m (x, y, z), and stays inside that box. Colours are neutral equipment greys,
never an ISA-101 status colour. The output is deterministic; ``tests/unit/test_scenery.py``
rebuilds it byte for byte.

Training and demo tool; not a safety-rated simulation.
"""

from __future__ import annotations

import argparse
import importlib.util
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
OUT = REPO / "scenes" / "examples" / "models" / "mixer-drive.glb"
LICENSE = """\
Author: HIS Controls (Hunt Integrative Solutions, LLC), for OpenFactory
License: CC-BY-4.0 (https://creativecommons.org/licenses/by/4.0/)
Source: generated by tools/make_item_mesh.py in this repository; no outside asset.
"""


def _models():
    spec = importlib.util.spec_from_file_location("make_models", REPO / "tools" / "make_models.py")
    module = importlib.util.module_from_spec(spec)  # type: ignore[arg-type]
    spec.loader.exec_module(module)  # type: ignore[union-attr]
    return module


def build() -> bytes:
    """The drive, in metres, in the scenery body's frame (y up, the motor along +x)."""
    m = _models()
    g = m.Geometry()
    g.box(m.DARK, (-0.5, -0.4, -0.3), (0.5, -0.35, 0.3))  # base plate
    g.box(m.STRUCTURE, (-0.45, -0.35, -0.24), (0.02, 0.18, 0.24))  # gearbox
    g.cylinder(m.ALUMINIUM, 0, (0.24, -0.08, 0.0), 0.19, 0.42)  # motor frame
    g.cylinder(m.DARK, 0, (0.47, -0.08, 0.0), 0.17, 0.06)  # fan cover
    g.box(m.FRAME, (0.12, 0.11, -0.08), (0.32, 0.24, 0.08))  # terminal box
    g.cylinder(m.FRAME, 1, (-0.21, 0.27, 0.0), 0.13, 0.18)  # output flange on top
    g.cylinder(m.ALUMINIUM, 1, (-0.21, 0.385, 0.0), 0.04, 0.03)  # shaft end
    return m.glb({"mixer-drive": g}, "tools/make_item_mesh.py")


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="exit 1 if a file differs")
    args = parser.parse_args(argv)
    wanted = {OUT: build(), OUT.with_name(OUT.name + ".license.txt"): LICENSE.encode("utf-8")}
    if args.check:
        stale = [p for p, data in wanted.items() if not p.is_file() or p.read_bytes() != data]
        for p in stale:
            print(
                f"{p.relative_to(REPO)} is not current; run tools/make_item_mesh.py",
                file=sys.stderr,
            )
        return 1 if stale else 0
    for path, data in wanted.items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_bytes(data)
        print(f"wrote {path.relative_to(REPO)} ({len(data)} bytes)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
