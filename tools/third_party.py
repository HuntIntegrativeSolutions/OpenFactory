"""Regenerate THIRD_PARTY.md from pip-licenses (Python) and license-checker (web).

Usage (from the repo root, after ``uv sync --all-extras`` and ``npm install`` in ``web/``)::

    uv run python tools/third_party.py --license-checker <path>/license-checker/bin/license-checker

``--license-checker`` is the path to license-checker 25.0.1's bin script, installed anywhere outside
``web/`` (for example ``npm install --prefix /tmp/lc license-checker@25.0.1``). It is not a project
dependency because it is only needed to refresh this file.

Exits 1 if any package declares a license outside the ADR-0001 allowlist (:data:`ALLOWED_FAMILIES`,
plus LGPL for the dynamically imported packages in :data:`LGPL_DYNAMIC`).

3D models (PLAN 2.15): every ``.glb`` tracked in the repository carries a sidecar
``<file>.license.txt`` with ``Author:``, ``License:`` and ``Source:`` lines, and the last section of
THIRD_PARTY.md lists them from those sidecars. ``--models`` rewrites only that section and needs
neither pip-licenses nor license-checker, so adding a mesh does not refresh the package tables.
Either mode exits 1 when a tracked ``.glb`` has no sidecar or a sidecar lacks one of the lines.
Both modes also write ``ATTRIBUTION.md`` (PLAN 4.2) from the same sidecars: the attribution each
model's license asks for (CC-BY-4.0: title, author, source, license), one entry per file.
"""

from __future__ import annotations

import argparse
import json
import re
import subprocess
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
OUT = REPO / "THIRD_PARTY.md"
SELF = {"openfactory", "openfactory-viewer"}


HEADER = """\
# Third-Party Software

OpenFactory is Apache-2.0 (code) and CC-BY-4.0 (3D models, textures, docs). This file
lists every third-party package it depends on, with the license each package declares.
Generated by `tools/third_party.py` from `pip-licenses` and `license-checker`; do not
edit by hand. Licenses are as declared in package metadata; check the upstream LICENSE
file before relying on an entry for a distribution decision.

## Notes

- **asyncua (LGPL-3.0-or-later)** is an optional extra (`openfactory[opcua]`).
  OpenFactory only imports it as an unmodified Python package (dynamic use, no static
  linking or vendoring), which LGPL permits from Apache-2.0 code. Users may replace it
  with any compatible version.
- **pycomm3 (MIT)** is an optional extra (`openfactory[logix]`).
- **MPL-2.0** packages in the web list are build-time tools only; none is bundled into
  the viewer.
- `@types/three` depends on its own `@dimforge/rapier3d-compat` 0.12.x for type
  definitions only. It is not bundled; the viewer uses 0.21.0.
- **OpenPLC Runtime (GPL-3.0)** is not a dependency. It runs as a separate process and
  talks to OpenFactory over Modbus TCP only.
- Dev and build tools are listed for completeness; they are not distributed.
- `tools/third_party.py` fails if any license falls outside the ADR-0001 allowlist: MIT,
  MIT-0, BSD, ISC, PSF-2.0, Apache-2.0, MPL-2.0, or LGPL used dynamically (asyncua only).
"""


#: License families allowed by ADR-0001 (as amended 2026-10-25).
ALLOWED_FAMILIES = ("MIT", "MIT-0", "BSD", "ISC", "PSF-2.0", "Apache-2.0", "MPL-2.0")
#: LGPL is allowed only for these packages, which OpenFactory imports dynamically and never vendors.
LGPL_DYNAMIC = {"asyncua"}
#: Licenses of runtime packages not installed on Linux (environment markers), checked by hand
#: against PyPI metadata. Re-verify when the pinned version changes.
REVIEWED = {"colorama": ("0.4.6", "BSD License")}

_FAMILY_PATTERNS = [
    ("MIT-0", r"^MIT-0$|MIT No Attribution"),
    ("MIT", r"^MIT( License)?$|^Expat"),
    ("BSD", r"^0BSD$|^BSD$|^BSD-[23]-Clause|BSD License"),  # not BSD-4-Clause
    ("ISC", r"^ISC"),
    ("PSF-2.0", r"^PSF-2\.0$|Python Software Foundation"),
    ("Apache-2.0", r"^Apache-2\.0$|Apache Software License|^Apache License,? (Version )?2"),
    ("MPL-2.0", r"^MPL-2\.0$|Mozilla Public License 2"),
    ("LGPL", r"LGPL|Lesser General Public License"),
]


def license_family(term: str) -> str | None:
    term = term.strip().strip("()").strip()
    for family, pattern in _FAMILY_PATTERNS:
        if re.search(pattern, term):
            return family
    return None


def license_problem(package: str, expression: str) -> str | None:
    """None if the declared license is allowed, else a reason.

    ``AND`` terms must all be allowed. ``OR``, ``;`` (several trove classifiers), and ``/``
    (license-checker arrays) list alternatives, so one allowed alternative is enough.
    """
    for conjunct in re.split(r"\s+AND\s+", expression.strip().strip("()")):
        options = [o for o in re.split(r"\s+OR\s+|;|\s/\s", conjunct) if o.strip()]
        families = {license_family(o) for o in options}
        allowed = set(ALLOWED_FAMILIES) | ({"LGPL"} if norm(package) in LGPL_DYNAMIC else set())
        if not families & allowed:
            return f"{package}: {conjunct.strip()!r} is not in the ADR-0001 allowlist"
    return None


def norm(name: str) -> str:
    return re.sub(r"[-_.]+", "-", name).lower()


def run(cmd: list[str], cwd: Path = REPO) -> str:
    return subprocess.run(cmd, cwd=cwd, check=True, capture_output=True, text=True).stdout


def python_runtime() -> dict[str, tuple[str, str]]:
    """Runtime closure (all extras, no dev group): name -> (version, environment marker)."""
    text = run(
        [
            "uv",
            "export",
            "--no-dev",
            "--all-extras",
            "--no-hashes",
            "--no-emit-project",
            "--format",
            "requirements-txt",
        ]
    )
    out: dict[str, tuple[str, str]] = {}
    for line in text.splitlines():
        m = re.match(r"^([A-Za-z0-9_.\-]+)==([^\s;]+)\s*(?:;\s*(.*))?$", line.strip())
        if m:
            out[norm(m[1])] = (m[2], m[3] or "")
    return out


def python_licenses() -> dict[str, dict[str, str]]:
    text = run(["uv", "run", "pip-licenses", "--from=mixed", "--format=json", "--with-urls"])
    return {norm(p["Name"]): p for p in json.loads(text) if norm(p["Name"]) not in SELF}


def npm_licenses(checker: Path, production: bool) -> dict[str, dict[str, str]]:
    cmd = ["node", str(checker), "--start", str(REPO / "web"), "--json"]
    if production:
        cmd.append("--production")
    data = json.loads(run(cmd))
    return {k: v for k, v in data.items() if k.rsplit("@", 1)[0] not in SELF}


MODELS_HEADING = "## 3D models (in this repository)"
MODEL_FIELDS = ("Author", "License", "Source")


def model_files() -> list[Path]:
    out = run(["git", "ls-files", "*.glb"])
    return sorted(REPO / line for line in out.splitlines() if line)


def models_section() -> tuple[list[str], list[str]]:
    """The 3D-models section's lines, and problems (a mesh with no usable sidecar)."""
    rows, problems = [], []
    for mesh in model_files():
        rel = mesh.relative_to(REPO).as_posix()
        sidecar = mesh.with_name(mesh.name + ".license.txt")
        if not sidecar.is_file():
            problems.append(f"{rel}: no {sidecar.name}")
            continue
        found = dict(
            line.split(":", 1)
            for line in sidecar.read_text(encoding="utf-8").splitlines()
            if ":" in line
        )
        fields = [found.get(f, "").strip() for f in MODEL_FIELDS]
        if not all(fields):
            problems.append(f"{rel}: {sidecar.name} needs {', '.join(MODEL_FIELDS)} lines")
            continue
        rows.append(f"| `{rel}` | {' | '.join(fields)} |")
    lines = [
        MODELS_HEADING,
        "",
        "Each file's record is its sidecar `<file>.license.txt`; `openfactory lint` warns",
        "(W209) on a scene mesh with neither a sidecar nor an entry here.",
        "",
        "| File | Author | License | Source |",
        "|------|--------|---------|--------|",
        *rows,
        "",
    ]
    return lines, problems


ATTRIBUTION = REPO / "ATTRIBUTION.md"
LICENSE_URLS = {
    "CC-BY-4.0": "https://creativecommons.org/licenses/by/4.0/",
    "CC0-1.0": "https://creativecommons.org/publicdomain/zero/1.0/",
}


def model_records() -> list[tuple[str, dict[str, str]]]:
    """(path, {Author, License, Source}) for every tracked .glb with a complete sidecar."""
    out = []
    for mesh in model_files():
        sidecar = mesh.with_name(mesh.name + ".license.txt")
        if not sidecar.is_file():
            continue
        found = {
            k.strip(): v.strip()
            for k, v in (
                line.split(":", 1)
                for line in sidecar.read_text(encoding="utf-8").splitlines()
                if ":" in line
            )
        }
        if all(found.get(f) for f in MODEL_FIELDS):
            out.append((mesh.relative_to(REPO).as_posix(), found))
    return out


def attribution_text() -> str:
    """ATTRIBUTION.md: the credit line each model's license asks for, from its sidecar."""
    lines = [
        "# Attribution",
        "",
        "The 3D models in this repository, with the attribution their licenses ask for. Generated",
        "by `tools/third_party.py --models` from each file's `<file>.license.txt` sidecar (the",
        'same records as THIRD_PARTY.md\'s "3D models" section); do not edit by hand. A copy or',
        "adaptation of a CC-BY model keeps its line, with a note of any change.",
        "",
        "OpenFactory is a training and demo tool, not a safety-rated simulation.",
        "",
    ]
    for path, record in model_records():
        license_ = record["License"]
        spdx = license_.split()[0]  # a sidecar may follow the identifier with its URL
        url = LICENSE_URLS.get(spdx)
        named = f"[{spdx}]({url})" if url else license_
        lines += [
            f"- **`{path}`** by {record['Author']}, licensed under {named}.",
            f"  Source: {record['Source'].rstrip('.')}.",
        ]
    return "\n".join(lines) + "\n"


def write_models_section() -> list[str]:
    """Replace (or append) the 3D-models section of THIRD_PARTY.md and rewrite ATTRIBUTION.md;
    return problems."""
    lines, problems = models_section()
    text = OUT.read_text(encoding="utf-8")
    head = text.split(MODELS_HEADING)[0].rstrip("\n") + "\n\n"
    OUT.write_text(head + "\n".join(lines), encoding="utf-8")
    ATTRIBUTION.write_text(attribution_text(), encoding="utf-8")
    return problems


def table(rows: list[tuple[str, str, str, str]]) -> list[str]:
    lines = ["| Package | Version | License | Source |", "|---------|---------|---------|--------|"]
    lines += [f"| {n} | {v} | {lic} | {url} |" for n, v, lic, url in rows]
    return lines


def main() -> int:
    if "--models" in sys.argv[1:]:
        problems = write_models_section()
        print(f"wrote the 3D-models section of {OUT}: {len(model_files())} file(s)")
        if problems:
            print("3D models without a license record:", *problems, sep="\n  ", file=sys.stderr)
            return 1
        return 0
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--license-checker", type=Path, required=True)
    args = parser.parse_args()

    runtime = python_runtime()
    installed = python_licenses()
    py_runtime, py_dev = [], []
    for key, info in sorted(installed.items()):
        lic = info["License"]
        marker = runtime[key][1] if key in runtime else ""
        if marker:  # installed here for another reason (a dev tool needs it), runtime only there
            lic = f"{lic} (runtime dependency only when {marker})"
        row = (info["Name"], info["Version"], lic, info.get("URL", ""))
        (py_runtime if key in runtime else py_dev).append(row)
    for key, (version, marker) in sorted(runtime.items()):
        if key not in installed:  # platform-specific, not installed on the generating host
            reviewed_version, reviewed_license = REVIEWED.get(key, ("", ""))
            if reviewed_version == version:
                lic = f"{reviewed_license} (reviewed on PyPI; installed only when {marker})"
            else:
                lic = f"UNKNOWN: not installed here ({marker}); review it and add to REVIEWED"
            py_runtime.append((key, version, lic, ""))
    py_runtime.sort(key=lambda r: norm(r[0]))

    npm_prod = npm_licenses(args.license_checker, production=True)
    npm_all = npm_licenses(args.license_checker, production=False)

    def npm_rows(data: dict[str, dict[str, str]]) -> list[tuple[str, str, str, str]]:
        rows = []
        for key, info in sorted(data.items()):
            name, version = key.rsplit("@", 1)
            lic = info.get("licenses", "")
            rows.append(
                (
                    name,
                    version,
                    lic if isinstance(lic, str) else " / ".join(lic),
                    info.get("repository", ""),
                )
            )
        return rows

    problems = [
        p
        for name, _version, lic, _url in py_runtime + py_dev + npm_rows(npm_all)
        if (p := license_problem(name, lic.split(" (reviewed")[0]))
    ]

    lines = [
        *HEADER.splitlines(),
        "## Python runtime (core and optional extras)",
        "",
        *table(py_runtime),
        "",
        "## Python development tools (not distributed)",
        "",
        *table(py_dev),
        "",
        "## Web viewer runtime (bundled into `web/dist`)",
        "",
        *table(npm_rows(npm_prod)),
        "",
        "## Web build tools (not distributed)",
        "",
        *table(npm_rows({k: v for k, v in npm_all.items() if k not in npm_prod})),
        "",
        *(models := models_section())[0],
    ]
    problems += models[1]
    OUT.write_text("\n".join(lines), encoding="utf-8")
    ATTRIBUTION.write_text(attribution_text(), encoding="utf-8")
    print(
        f"wrote {OUT}: {len(py_runtime)} Python runtime, {len(py_dev)} Python dev, "
        f"{len(npm_prod)} web runtime, {len(npm_all) - len(npm_prod)} web build"
    )
    if problems:
        print("licenses outside the ADR-0001 allowlist:", *problems, sep="\n  ", file=sys.stderr)
        return 1
    print(
        f"all licenses within the ADR-0001 allowlist: {', '.join(ALLOWED_FAMILIES)}, "
        f"LGPL (dynamic only: {', '.join(sorted(LGPL_DYNAMIC))})"
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
